    public static string[]? Glyph(char c) => Glyphs.GetValueOrDefault(char.ToUpperInvariant(c));

    public static int Measure(string text) => Math.Max(0, text.Length * 5 - 1);

    public static void Draw(PixelImage img, int x, int y, string text, uint color)
    {
        foreach (char c in text)
        {
            if (Glyph(c) is { } g) img.Pattern(x, y, g, color);
            x += 5;
        }
    }

    public static void DrawCentered(PixelImage img, int cx, int y, string text, uint color) =>
        Draw(img, cx - Measure(text) / 2, y, text, color);
